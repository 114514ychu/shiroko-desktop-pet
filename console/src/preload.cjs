const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('petConsole', {
  assistant: value => ipcRenderer.invoke('console:assistant',value),
  onAssistantChanged: callback => ipcRenderer.on('console:assistant-changed',()=>callback()),
  onAssistantOpen: callback => ipcRenderer.on('console:assistant-open',()=>callback()),
  history: value => ipcRenderer.invoke('console:history',value),
  onHistoryChanged: callback => ipcRenderer.on('console:history-changed',()=>callback()),
  onHistoryOpen: callback => ipcRenderer.on('console:history-open',(_event,id)=>callback(id)),
  acknowledge: () => ipcRenderer.invoke('console:acknowledge'),
  removalPrompt: id => ipcRenderer.invoke('console:removal-prompt', id),
  remove: id => ipcRenderer.invoke('console:package-remove', id),
  library: value => ipcRenderer.invoke('console:library', value),
  install: id => ipcRenderer.invoke('console:package-install', id),
  cancelInstall: id => ipcRenderer.invoke('console:package-cancel', id),
  refreshCatalog: () => ipcRenderer.invoke('console:package-refresh'),
  initial: () => ipcRenderer.invoke('console:initial'),
  selection: value => ipcRenderer.invoke('console:selection', value),
  theme: value => ipcRenderer.invoke('console:theme', value),
  volume: value => ipcRenderer.invoke('console:volume', value),
  settings: value => ipcRenderer.invoke('console:settings', value),
  command: (id, name, value) => ipcRenderer.invoke('console:command', { id, name, value }),
  details: id => ipcRenderer.invoke('console:details', id),
  back: () => ipcRenderer.invoke('console:back'),
  retry: id => ipcRenderer.invoke('console:retry', id),
  hide: () => ipcRenderer.send('console:hide'),
  quit: () => ipcRenderer.send('console:quit'),
  previewTargets: ids => ipcRenderer.send('console:preview-targets', ids),
  onState: callback => ipcRenderer.on('console:state', (_event, value) => callback(value)),
  onPreview: callback => ipcRenderer.on('console:preview', (_event, value) => callback(value)),
  onSettingsClosed: callback => ipcRenderer.on('console:settings-closed', () => callback()),
  onSettingsFocus: callback => ipcRenderer.on('console:settings-focus', () => callback())
});
